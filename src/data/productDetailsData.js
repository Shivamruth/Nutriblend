export const getProductExtraDetails = (product) => {
  if (!product) return null;

  const productName = product.name || product.product_name || "";

  const exactMatch = productDetailsData[productName];

  if (exactMatch) return exactMatch;

  const foundKey = Object.keys(productDetailsData).find((key) =>
    productName.toLowerCase().includes(key.toLowerCase())
  );

  if (foundKey) return productDetailsData[foundKey];

  return null;
};